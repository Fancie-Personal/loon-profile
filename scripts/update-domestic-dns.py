#!/usr/bin/env python3
"""Generate encrypted domestic DNS mappings from the existing China domain set."""
from datetime import date
from pathlib import Path
import re
import urllib.request

SOURCE = "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/Loon/China/China_Domain.list"
DEST = Path(__file__).resolve().parents[1] / "plugins/domestic-dns.plugin"
DNS = "https://223.5.5.5/dns-query"
# These services already use the Apple/DIRECT policy in this profile.
APPLE = {
    "apple.com", "apple.com.cn", "icloud.com", "icloud.com.cn", "itunes.com",
    "mzstatic.com", "cdn-apple.com", "aaplimg.com", "apple-dns.net",
    "apple-cloudkit.com", "apple-mapkit.com",
}


def main():
    text = urllib.request.urlopen(SOURCE, timeout=30).read().decode("utf-8-sig")
    suffixes, exact = set(APPLE), set()
    count = 0
    for raw in text.splitlines():
        domain = raw.strip().lower()
        if not domain or domain.startswith("#"):
            continue
        if not re.fullmatch(r"\.?[a-z0-9-]+(?:\.[a-z0-9-]+)+", domain):
            raise ValueError(f"Unexpected source domain: {domain!r}")
        count += 1
        if domain.startswith("."):
            suffixes.add(domain[1:])
        else:
            exact.add(domain)
    if count < 1000:
        raise ValueError("Incomplete China domain set")

    # Cover .cn even when a new domestic service is not in the source yet.
    suffixes.add("cn")
    roots = {d for d in suffixes if not any(
        ".".join(d.split(".")[i:]) in suffixes
        for i in range(1, len(d.split(".")))
    )}
    exact = {d for d in exact if not any(
        d == root or d.endswith("." + root) for root in roots
    )}
    patterns = set(exact)
    for root in roots:
        if "." in root:
            patterns.add(root)
        patterns.add("*." + root)

    header = f"""#!name = 国内加密 DNS 分流
#!desc = 国内直连域名与 Apple 服务使用阿里 DoH；其他域名沿用主配置的境外 DoH。
#!author = Fancie-Personal; domain data by blackmatrix7
#!homepage = https://github.com/Fancie-Personal/loon-profile
#!date = {date.today().isoformat()}
# Generated by scripts/update-domestic-dns.py; do not edit manually.
# Domain source: {SOURCE}
# Adds DNS mappings only; does not bypass DNS interception or change routing.

[Host]
"""
    DEST.write_text(header + "".join(
        f"{pattern} = server:{DNS}\n" for pattern in sorted(patterns)
    ))
    print(f"Generated {len(patterns)} Host mappings from {count} China domains and Apple service domains")


if __name__ == "__main__":
    main()
